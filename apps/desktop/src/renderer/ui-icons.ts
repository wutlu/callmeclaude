export type IconName = keyof typeof P;

/** An inline SVG icon; `cls` adds classes (size, spin). */
export function icon(name: string, cls = ''): string {
  return `<svg class="i ${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${P[name] ?? P.circle}</svg>`;
}

/** Session state → icon, like the phone apps. */
export function stateIcon(state: string): string {
  switch (state) {
    case 'running':
      return icon('spinner', 'spin');
    case 'waiting_permission':
    case 'waiting_input':
      return icon('question');
    case 'blocked':
    case 'errored':
      return icon('alert');
    case 'done':
      return icon('done');
    case 'stale':
      return icon('moon');
    default:
      return icon('circle');
  }
}
